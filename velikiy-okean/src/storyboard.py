def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def mmss(x):
    m = int(x // 60)
    return f'{m}:{x - 60 * m:05.2f}'


def build():
    rows = []
    for i, s in enumerate(SHOTS):
        t0 = s[0]
        f0 = round(t0 * FPS)
        f1 = (round(SHOTS[i + 1][0] * FPS) - 1) if i + 1 < len(SHOTS) else LAST_FRAME
        t1 = (f1 + 1) / FPS if i + 1 < len(SHOTS) else END_T
        rows.append(dict(shot=f'{i + 1:02d}', section=s[1], title=s[2], start_s=round(f0 / FPS, 3), end_s=round(t1, 3),
                         start_tc=mmss(f0 / FPS), end_tc=mmss(t1), start_frame=f0, end_frame=f1, frames=f1 - f0 + 1,
                         dur_s=round((f1 - f0 + 1) / FPS, 3), size_lens=s[3], camera=s[4], action=s[5], light=s[6],
                         light_desc=' → '.join(LIGHT[k] for k in s[6].split('→')), transition=s[7], motivation=s[8]))
    return rows


